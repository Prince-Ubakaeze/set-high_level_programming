#!/usr/bin/python3
"""Provide basic arithmetic functions."""


def add(a, b):
    """Return a plus b."""
    return a + b


def sub(a, b):
    """Return a minus b."""
    return a - b


def mul(a, b):
    """Return a multiplied by b."""
    return a * b


def div(a, b):
    """Return integer division of a by b using task behaviour."""
    return int(a / b)
